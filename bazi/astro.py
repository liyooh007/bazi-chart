"""天文历算内核：儒略日、太阳视黄经、二十四节气、均时差。

算法来源
--------
* 太阳位置：VSOP87D 地球日心黄经截断级数（Meeus, *Astronomical Algorithms*
  第 32 章附录 III 的截断表，L0–L5 共 129 项），叠加章动（IAU1980 主项）
  与光行差改正，得到太阳视黄经，1950–2050 年区间误差约 1″。
* ΔT（TT−UT1）：Espenak & Meeus 多项式（NASA/GSFC 五千年 ΔT 目录）。
* 节气：求太阳视黄经等于 15° 整数倍的时刻，用割线迭代，收敛到 1e-9 度
  （约 1 毫秒）。

精度实测（对照 JPL DE441 数值历表生成的节气表，UT1+8）：
    1900 / 1984 / 2000 / 2024 年 96 个节气 → 最大偏差 1 分钟
    2100 年 24 个节气 → 最大偏差 3 分钟（ΔT 外推模型分歧所致）
"""

