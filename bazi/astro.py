def _series(terms, tau: float) -> float:
    s = 0.0
    for a, b, c in terms:
        s += a * math.cos(b + c * tau)
    return s


def earth_heliocentric_longitude(tau: float) -> float:
    """地球日心黄经（弧度），tau = 儒略千年数（自 J2000，TT）。"""
    return (_series(_L0, tau) + _series(_L1, tau) * tau + _series(_L2, tau) * tau ** 2
            + _series(_L3, tau) * tau ** 3 + _series(_L4, tau) * tau ** 4
            + _series(_L5, tau) * tau ** 5) / 1e8


def nutation_in_longitude(t: float) -> float:
    """黄经章动 Δψ（角秒）。t = 儒略世纪数（自 J2000）。"""
    ls = (280.4665 + 36000.7698 * t) * RAD
    lm = (218.3165 + 481267.8813 * t) * RAD
    om = (125.04452 - 1934.136261 * t) * RAD
    return (-17.20 * math.sin(om) - 1.32 * math.sin(2 * ls)
            - 0.23 * math.sin(2 * lm) + 0.21 * math.sin(2 * om))


def sun_apparent_longitude(jd_tt: float) -> float:
    """太阳视黄经（度，0–360），输入为力学时 TT 的儒略日。"""
    t = (jd_tt - 2451545.0) / 36525.0
    lon = earth_heliocentric_longitude(t / 10.0) + math.pi
    lon += (-0.09033 / 3600.0) * RAD                       # FK5 系统差
    lon += (nutation_in_longitude(t) / 3600.0) * RAD       # 章动
    lon -= (20.4898 / 3600.0) * RAD                        # 光行差
    return math.degrees(lon) % 360.0


def _tt_to_ut(jd_tt: float) -> float:
    year = 2000.0 + (jd_tt - 2451545.0) / 365.25
    return jd_tt - delta_t(year) / 86400.0


def _ut_to_tt(jd_ut: float) -> float:
    year = 2000.0 + (jd_ut - 2451545.0) / 365.25
    return jd_ut + delta_t(year) / 86400.0


# --------------------------------------------------------------------------- #
# 节气求解
# --------------------------------------------------------------------------- #
def solar_term_jd(target_deg: float, jd_guess: float, tol: float = 1e-9) -> float:
    """求太阳视黄经 = ``target_deg`` 的儒略日（UT）。

    ``jd_guess`` 只需在真值 ±20 天内。使用割线迭代（太阳日行约 0.9856°）。
    """
    jd = jd_guess
    for _ in range(80):
        lam = sun_apparent_longitude(_ut_to_tt(jd))
        diff = (lam - target_deg + 180.0) % 360.0 - 180.0
        if abs(diff) < tol:
            break
        jd -= diff / 0.98564733
    return jd


def solar_term_datetime(year: int, term_index: int, tz_hours: float = CST_OFFSET) -> datetime:
    """求某公历年某节气的时刻（本地时区）。

    ``term_index``：SOLAR_TERMS 中的下标（0=立春）。注意"小寒/大寒"属于
    公历 1 月，而"立春"起为该公历年的第 3 个节气，调用方需自行处理归属。
    """
    name = SOLAR_TERMS[term_index % 24]
    target = TERM_LONGITUDE[term_index % 24]
    # 立春(0)–大寒(23) 依次跨越 2 月–次年 1 月；粗略起点：2 月 4 日 + 15.2 天 * i
    base_jd = jd_from_datetime(datetime(year, 2, 4))
    guess = base_jd + 15.2184 * (term_index % 24)
    if term_index >= 22:            # 小寒、大寒落在同年 1 月
        base_jd = jd_from_datetime(datetime(year, 1, 6))
        guess = base_jd + 15.2184 * (term_index - 22)
    jd_ut = solar_term_jd(target, guess)
    return datetime_from_jd(jd_ut + tz_hours / 24.0)


def terms_of_year(year: int, tz_hours: float = CST_OFFSET) -> dict[str, datetime]:
    """返回公历年 ``year`` 内 24 个节气的时刻（按 1 月—12 月顺序）。"""
    out: dict[str, datetime] = {}
    # 小寒、大寒（1 月）
    out["小寒"] = solar_term_datetime(year, 22, tz_hours)
    out["大寒"] = solar_term_datetime(year, 23, tz_hours)
    # 立春 … 冬至（2 月—12 月）
    for i in range(22):
        out[SOLAR_TERMS[i]] = solar_term_datetime(year, i, tz_hours)
    return out


# --------------------------------------------------------------------------- #
# 均时差
# --------------------------------------------------------------------------- #
def equation_of_time(jd_ut: float) -> float:
    """均时差（分钟）：真太阳时 − 平太阳时。范围约 ±16.4 分钟。"""
    jd_tt = _ut_to_tt(jd_ut)
    t = (jd_tt - 2451545.0) / 36525.0
    tau = t / 10.0
    l0 = (280.4664567 + 360007.6982779 * tau + 0.03032028 * tau ** 2
          + tau ** 3 / 49931.0 - tau ** 4 / 15300.0 - tau ** 5 / 2000000.0) % 360.0
    lam = sun_apparent_longitude(jd_tt)
    eps = (23.0 + 26.0 / 60.0 + 21.448 / 3600.0
           + (-46.8150 * t - 0.00059 * t ** 2 + 0.001813 * t ** 3) / 3600.0)
    lam_r, eps_r = lam * RAD, eps * RAD
    alpha = math.degrees(math.atan2(math.cos(eps_r) * math.sin(lam_r),
                                    math.cos(lam_r))) % 360.0
    e = l0 - 0.0057183 - alpha + nutation_in_longitude(t) / 3600.0 * math.cos(eps_r)
    return ((e + 180.0) % 360.0 - 180.0) * 4.0
