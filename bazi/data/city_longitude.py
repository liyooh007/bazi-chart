def lookup_longitude(name: str | None) -> float | None:
    """按城市短名查经度；支持带“市/州/盟/地区”后缀与去空白。查不到返回 None。"""
    if not name:
        return None
    key = name.strip()
    if key in CITY_LONGITUDE:
        return CITY_LONGITUDE[key]
    # ponytail: “地名+X族自治州/县”里民族名长度不定（白/哈尼/哈尼彝…），
    # 纯按“族”字符无法切分地名与族名（“大理白”不知边界），只能列已知民族名最长匹配。
    _ETHNIC = ("壮族", "满族", "回族", "苗族", "维吾尔族", "土家族", "彝族", "藏族",
               "蒙古族", "侗族", "布依族", "瑶族", "白族", "朝鲜族", "哈尼族", "黎族",
               "哈萨克族", "傣族", "畲族", "傈僳族", "东乡族", "仡佬族", "拉祜族", "佤族",
               "水族", "纳西族", "羌族", "土族", "仫佬族", "锡伯族", "柯尔克孜族", "景颇族",
               "达斡尔族", "撒拉族", "布朗族", "毛南族", "塔吉克族", "普米族", "阿昌族",
               "怒族", "鄂温克族", "京族", "基诺族", "德昂族", "保安族", "俄罗斯族",
               "裕固族", "乌孜别克族", "门巴族", "鄂伦春族", "独龙族", "赫哲族", "高山族",
               "珞巴族", "塔塔尔族")
    for _ in range(3):
        if key.endswith(("自治州", "自治县")):
            stem = key[:-3]
            # 一次剥完尾部连续的多个族名（红河哈尼族彝族 / 恩施土家族苗族）
            cand = stem
            changed = True
            while changed:
                changed = False
                hit = next((e for e in _ETHNIC if cand.endswith(e) and len(cand) > len(e)), None)
                if hit:
                    cand = cand[:-len(hit)]
                    changed = True
            if cand != stem:
                if cand in CITY_LONGITUDE:
                    return CITY_LONGITUDE[cand]
                key = cand
                continue
        for suf in ("特别行政区", "地区", "市", "州", "盟", "县"):
            if key.endswith(suf) and len(key) > len(suf):
                key = key[: -len(suf)]
                if key in CITY_LONGITUDE:
                    return CITY_LONGITUDE[key]
                break
        else:
            break
    return CITY_LONGITUDE.get(key)
