def _parse(raw: str) -> list[tuple[int, list[str]]]:
    """把 '1庚2壬甲3癸丁' 解析成 [(1,['庚']),(2,['壬','甲']),(3,['癸','丁'])]。"""
    out: list[tuple[int, list[str]]] = []
    rank = 0
    cur: list[str] = []
    for ch in raw:
        if ch.isdigit():
            if cur:
                out.append((rank, cur))
            rank, cur = int(ch), []
        elif ch == "_":
            continue  # 条件标记，天干随后给出即可
        elif ch in TIANGAN:
            cur.append(ch)
        # “夜生贵”这类汉字注脚忽略，只留天干
    if cur:
        out.append((rank, cur))
    return out


def qiongtong(day_gan: str, month_zhi: str) -> dict:
    """查《穷通宝鉴》某日干生于某月令的调候用神。

    返回::

        {"key": "甲戌", "primary": "庚",
         "assist": ["壬","甲","癸","丁"], "ranks": [(1,["庚"]),...],
         "raw": "1庚2壬甲3癸丁"}

    越界或缺表返回空 dict（不抛异常，调用方自行降级）。
    """
    key = day_gan + month_zhi
    raw = _RAW.get(key)
    if raw is None or day_gan not in TIANGAN or month_zhi not in DIZHI:
        return {}
    ranks = _parse(raw)
    primary = ranks[0][1][0] if ranks and ranks[0][1] else ""
    assist = [g for _, gs in ranks[1:] for g in gs]
    # raw 里的“_”是内部条件标记（如夜生），不展示给用户：按解析结果重建干净串
    display = "".join(str(r) + "".join(gs) for r, gs in ranks)
    return {"key": key, "primary": primary, "assist": assist,
            "ranks": ranks, "raw": display}


def all_cells() -> int:
    """暴露格子数，便于自检。"""
    return len(_RAW)


# ponytail: 天干五行映射在 constants 里按索引排布（木火土金水循环），这里直接
# 取 WUXING[TIANGAN.index(g)]，不另建表。
def qiongtong_wuxing(day_gan: str, month_zhi: str) -> dict:
    """同 :func:`qiongtong`，但把用神天干归并成五行（供评分/大运加权）。

    返回 ``{"primary":"金","assist":["水",...]}``；首要在 assist 中去重。
    缺表返回空 dict。
    """
    from .constants import WUXING as _W
    q = qiongtong(day_gan, month_zhi)
    if not q:
        return {}
    # TIANGAN 甲乙/丙丁/… 两两同五行，故 index//2 对应 WUXING
    g2w = lambda g: _W[TIANGAN.index(g) // 2]
    assist = []
    for w in (g2w(g) for g in q["assist"]):
        if w not in assist:
            assist.append(w)
    return {"primary": g2w(q["primary"]), "primary_gan": q["primary"],
            "assist": assist}
