def ganzhi(index: int) -> str:
    """干支索引 0..59 → 干支名。"""
    i = index % 60
    return TIANGAN[i % 10] + DIZHI[i % 12]


def ganzhi_index(gan: str, zhi: str) -> int:
    """由天干、地支求干支索引（0..59）。"""
    a, b = TIANGAN.index(gan), DIZHI.index(zhi)
    for i in range(60):
        if i % 10 == a and i % 12 == b:
            return i
    raise ValueError(f"{gan}{zhi} 不是合法干支组合")


def gan_wuxing(gan: str) -> str:
    return GAN_WUXING[TIANGAN.index(gan)]


def zhi_wuxing(zhi: str) -> str:
    return ZHI_WUXING[DIZHI.index(zhi)]


def nayin(ganzhi_name: str) -> str:
    """干支 → 纳音（如 '甲子' → '海中金'）。"""
    i = ganzhi_index(ganzhi_name[0], ganzhi_name[1])
    return NAYIN_30[i // 2]


def sheng(wx: str) -> str:
    """我生者。"""
    return WUXING_SHENG[wx]


def ke(wx: str) -> str:
    """我克者。"""
    return WUXING_KE[wx]


def sheng_wo(wx: str) -> str:
    """生我者。"""
    for a, b in WUXING_SHENG.items():
        if b == wx:
            return a
    raise ValueError(wx)


def ke_wo(wx: str) -> str:
    """克我者。"""
    for a, b in WUXING_KE.items():
        if b == wx:
            return a
    raise ValueError(wx)


def shishen(day_gan: str, other_gan: str) -> str:
    """以日干为主，求它干十神。"""
    dw, ow = gan_wuxing(day_gan), gan_wuxing(other_gan)
    same_polarity = GAN_YANG[TIANGAN.index(day_gan)] == GAN_YANG[TIANGAN.index(other_gan)]
    if dw == ow:
        return "比肩" if same_polarity else "劫财"
    if sheng(dw) == ow:                 # 我生
        return "食神" if same_polarity else "伤官"
    if ke(dw) == ow:                    # 我克
        return "偏财" if same_polarity else "正财"
    if ke_wo(dw) == ow:                 # 克我
        return "七杀" if same_polarity else "正官"
    if sheng_wo(dw) == ow:              # 生我
        return "偏印" if same_polarity else "正印"
    raise ValueError(f"无法归类 {day_gan} 与 {other_gan}")


def shishen_of_wuxing(day_gan: str, wx: str) -> str:
    """给定五行（非天干）时的十神归类别名，取同阴阳的一半。"""
    dw = gan_wuxing(day_gan)
    table = {dw: "比肩", sheng(dw): "食神", ke(dw): "偏财",
             ke_wo(dw): "七杀", sheng_wo(dw): "偏印"}
    return table[wx]


def changsheng(gan: str, zhi: str) -> str:
    """天干在某地支的十二长生状态。"""
    start = DIZHI.index(CHANGSHENG_START[gan])
    forward = GAN_YANG[TIANGAN.index(gan)]
    step = (DIZHI.index(zhi) - start) % 12
    if not forward:
        step = (-step) % 12
    return CHANGSHENG_12[step]


def xunkong(gan: str, zhi: str) -> tuple[str, str]:
    """旬空（空亡）：返回该干支所在旬的两个空亡地支。"""
    g, z = TIANGAN.index(gan), DIZHI.index(zhi)
    xun_start = (z - g) % 12          # 旬首地支（甲子旬为子）
    return DIZHI[(xun_start + 10) % 12], DIZHI[(xun_start + 11) % 12]


def constellation(month: int, day: int) -> str:
    """公历月日 → 星座（12 月 22 日–1 月 19 日为摩羯座）。"""
    name = "摩羯座"
    for m, d, n in CONSTELLATIONS:
        if (month, day) >= (m, d):
            name = n
    return name


def zhi_hour(hour: int) -> int:
    """小时（0-23）→ 时支索引。23 点起为子时。"""
    return ((hour + 1) // 2) % 12


def relations(zhi_a: str, zhi_b: str) -> list[str]:
    """两地支关系（冲/合/害/刑/半合/三合/三会需三支，此处只判两两关系）。"""
    a, b = DIZHI.index(zhi_a), DIZHI.index(zhi_b)
    out = []
    if (min(a, b), max(a, b)) in ZHI_CHONG:
        out.append("六冲")
    if frozenset((a, b)) in ZHI_HE:
        out.append("六合")
    if frozenset((a, b)) in BANHE:
        out.append("半合")
    if (min(a, b), max(a, b)) in ZHI_HAI:
        out.append("相害")
    if a == b:
        if a in XING_SELF:
            out.append("自刑")
        out.append("伏吟")
    for g in XING_GROUP:
        if a in g and b in g and a != b:
            out.append("三刑")
    return out
